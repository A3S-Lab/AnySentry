#!/usr/bin/env node

import assert from 'node:assert/strict';
import { ClickHouseStore } from '../apps/api/dist/security-monitoring/clickhouse-store.js';

const state = { rows: [], queries: [], inserts: [] };
const store = new ClickHouseStore();
store.ready = true;
store.client = {
  async query(options) {
    state.queries.push(structuredClone(options));
    return { async json() { return structuredClone(state.rows); } };
  },
  async insert(options) {
    state.inserts.push(structuredClone(options));
    return { executed: true };
  },
};

const invocationId = 'invocation-relation-s6';
const scope = {
  workspacePath: '/workspace/relation-s6',
  sourceId: 'source-relation-s6',
  agentInstanceId: 'runtime-relation-s6',
};
const updatedAt = Date.now() - 60_000;
const evidenceVersion = 'a'.repeat(64);
const items = [{
  invocationId,
  toolCallId: 'tool-relation-s6',
  toolName: 'write',
  startedAt: updatedAt - 2_000,
  endedAt: updatedAt - 1_000,
  status: 'linked',
  reason: 'exact_process_and_resource',
  adapterEventIds: ['adapter-relation-s6'],
  kernelEvidence: [{
    eventId: 'kernel-relation-s6', eventKind: 'FileAccess', at: updatedAt - 1_500,
    linkMethod: 'same_process_resource', confidence: 1,
  }],
}];

assert.equal(await store.writeToolEvidenceRelations(items, evidenceVersion, scope, updatedAt), true);
assert.equal(state.inserts.length, 1);
assert.equal(state.inserts[0].table, 'tool_evidence_relations');
assert.equal(state.inserts[0].values[0].workspacePath, scope.workspacePath);
assert.equal(state.inserts[0].values[0].agentInstanceId, scope.agentInstanceId);
assert.equal(JSON.parse(state.inserts[0].values[0].payload).relation, undefined,
  'relation metadata is generated by the durable reader rather than trusted from payload JSON');

state.rows = state.inserts[0].values;
const restored = await store.readToolEvidenceRelations(invocationId, undefined, scope);
assert.equal(restored?.items.length, 1);
assert.equal(restored?.items[0].kernelEvidence[0].eventId, 'kernel-relation-s6');
assert.deepEqual(restored?.items[0].relation, {
  schemaVersion: 'anysentry.tool_evidence_relation.v1',
  relationVersion: 2,
  evidenceVersion,
  updatedAt,
});
const relationQuery = state.queries.at(-1);
assert.match(relationQuery.query, /FROM tool_evidence_relations FINAL/u);
assert.match(relationQuery.query, /workspacePath = \{workspacePath:String\}/u);
assert.match(relationQuery.query, /agentInstanceId = \{agentInstanceId:String\}/u);
assert.match(relationQuery.query, /relationVersion = 2/u);
assert.equal(relationQuery.clickhouse_settings.max_execution_time, 2);
assert.equal(relationQuery.clickhouse_settings.max_memory_usage, String(64 * 1024 * 1024));

state.rows = [{ ...state.inserts[0].values[0], itemCount: 2 }];
assert.deepEqual(
  (await store.readToolEvidenceRelations(invocationId, undefined, scope))?.items,
  [],
  'an incomplete Invocation relation set fails closed and is recomputed from indexed evidence',
);

console.log('S6 durable ToolEvidence relation verification passed');
