import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { LocalRecordResourceSampler, parseResourceCounters } = require('../apps/api/dist/security-monitoring/local-record-resources.js');
const { LocalRecordTrackingService } = require('../apps/api/dist/security-monitoring/local-record-tracking.service.js');
const root = await mkdtemp(join(tmpdir(), 'anysentry-resource-test-'));
const stat = (generation, work) => { const fields = Array(30).fill('0'); fields[0]='S'; fields[11]=String(work); fields[19]=String(generation); return `42 (agent with spaces) ${fields.join(' ')}`; };
const host = ticks => `cpu ${ticks} 0 0 0 0 0 0 0 99 99\ncpu0 1\ncpu1 1\n`;
const now = Date.now;
let at = 1_000_000;
Date.now = () => at;
try {
  await mkdir(join(root,'42'));
  await writeFile(join(root,'42/status'),'VmRSS: 2048 kB\n');
  const update = async (generation, work, total) => {
    await writeFile(join(root,'42/stat'),stat(generation,work));
    await writeFile(join(root,'stat'),host(total));
  };
  assert.equal(parseResourceCounters(stat(100,10),'VmRSS: 2048 kB',host(100)).total,100,'guest counters are not added twice');
  const sampler = new LocalRecordResourceSampler();
  await update(100,10,100);
  let result = await sampler.read('record',root,42,'100');
  assert.equal(result.samples[0].cpuPercent,undefined,'first sample has no fabricated CPU');
  assert.equal(result.samples[0].rssBytes,2097152);
  at += 15_000; await update(100,20,200);
  result = await sampler.read('record',root,42,'100');
  assert.equal(result.samples[1].cpuPercent,20,'process ticks / host ticks * CPU count');
  const simultaneous = await Promise.all([sampler.read('record',root,42,'100'),sampler.read('record',root,42,'100')]);
  assert.equal(simultaneous[0].samples.length,2,'refreshes do not duplicate samples');
  at += 120_000; await update(100,50,300);
  assert.equal((await sampler.read('record',root,42,'100')).samples.at(-1).cpuPercent,undefined,'long gaps do not become current CPU');
  await update(101,5,400);
  assert.equal((await sampler.read('record',root,42,'100')).state,'unbound','PID reuse cannot inherit session identity');
  result = await sampler.read('record',root,42,'101');
  assert.equal(result.samples.length,1,'new generation starts a new history');
  assert.equal(result.samples[0].cpuPercent,undefined);
  assert.equal((await sampler.read('missing',root,99,'100')).state,'unavailable');
  const service = new LocalRecordTrackingService();
  service.isEnabled = () => true;
  service.discover = async () => ({entries:[{recordId:'a'},{recordId:'b'}]});
  service.configuredProcessRoot = () => root;
  service.processObservationStatus = async () => ({enabled:true,available:true});
  let bindings = new Map();
  service.scanProcesses = async () => ({available:true,exactByRecordId:bindings});
  assert.equal((await service.recordResources('a')).state,'unbound');
  const match={matchedPid:42,matchedStartTimeTicks:'101'};
  bindings = new Map([['a',[match]],['b',[match]]]);
  assert.equal((await service.recordResources('a')).state,'shared','shared process is not attributed to a single session');
  bindings = new Map([['a',[match,{matchedPid:43,matchedStartTimeTicks:'101'}]]]);
  assert.equal((await service.recordResources('a')).state,'unbound','multiple exact candidates remain unresolved');
  bindings = new Map([['a',[match]]]);
  assert.equal((await service.recordResources('a')).state,'observed');
  await assert.rejects(service.recordResources('unknown'),/local record not found/);
  console.log('Resource sampling: CPU normalization, missing data, bounded refresh, gaps and PID reuse passed.');
} finally { Date.now = now; await rm(root,{recursive:true,force:true}); }
